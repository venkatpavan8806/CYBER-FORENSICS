"""Benign synthetic ransomware-incident generator.

Generates a Mode B artifact folder (see ingest/artifact_folder.py for the
expected layout) that exercises all three extractors and the correlated
Rule-4 finding, WITHOUT any real malware, encryption, propagation, or
destructive capability whatsoever - this is a hard safety boundary from the
project spec (Section 2) and is not to be crossed.

What "attack" this mimics, and how each piece is faked:

  - Filesystem: a batch of plain files is (re)written with a fake extension
    (`.locked_demo` by default) and a `README_RESTORE_FILES.txt`-style dummy
    note is dropped alongside them. No file content is actually encrypted -
    the "encrypted" files just contain a placeholder string.
  - Registry: a private, throwaway hive file is created via
    simulate/hive_writer.py (real Windows Registry API, zero real system
    data - see that module's docstring) containing a fake Run-key autostart
    entry, a fake service with a non-standard ImagePath, and fake BAM
    execution evidence for vssadmin.exe.
  - Event log: a JSON file of "mocked event records" (see
    extractors/eventlog_vss.py) containing one record whose text resembles
    `vssadmin delete shadows /all` execution evidence.

All three are generated within the same short run of this function, so their
timestamps land in the same tight window by construction - which is exactly
what lets the correlation engine (Rule 4) prove it can tie a full attack
chain together end-to-end on a fixture with no external downloads required.
"""
from __future__ import annotations

import json
import platform
from datetime import datetime, timedelta, timezone
from pathlib import Path

from ransomtrace.simulate.hive_writer import (
    REG_BINARY,
    REG_SZ,
    HiveWriterUnavailable,
    SyntheticHiveBuilder,
    filetime_bytes,
)

RANSOM_NOTE_TEXT = (
    "*** THIS IS A SYNTHETIC TEST FILE GENERATED BY ransomtrace/simulate ***\n"
    "It is NOT a real ransom note and no files were actually encrypted.\n"
    "It exists solely to test that the filesystem extractor recognizes\n"
    "known ransom-note filename patterns.\n"
)

FAKE_ENCRYPTED_CONTENT = (
    b"*** SYNTHETIC TEST DATA - NOT REAL ENCRYPTED CONTENT - "
    b"generated by ransomtrace/simulate/synthetic_incident.py ***"
)

BENIGN_EXTENSIONS = ["txt", "docx", "jpg", "csv", "pdf"]

# Deliberately fake, obviously-not-real paths/names.
FAKE_RUN_VALUE_NAME = "SecurityUpdate"
FAKE_RUN_VALUE_DATA = r"C:\Users\Public\svchost_update.exe"
FAKE_SERVICE_NAME = "WinDefenderHelperSvc"
FAKE_SERVICE_IMAGE_PATH = r"C:\Users\Public\svchost_update.exe"
FAKE_SID = "S-1-5-21-1111111111-2222222222-3333333333-1001"


def _write_benign_files(files_dir: Path, count: int, base_time: datetime) -> None:
    for i in range(count):
        ext = BENIGN_EXTENSIONS[i % len(BENIGN_EXTENSIONS)]
        path = files_dir / f"document_{i:03d}.{ext}"
        path.write_bytes(f"synthetic benign test file {i}".encode("utf-8"))
        # Spread benign files across the past week so they never fall inside
        # the tight encryption-burst window.
        mtime = base_time - timedelta(days=1, hours=i % 24)
        _set_mtime(path, mtime)


def _write_encrypted_batch(
    files_dir: Path, count: int, extension: str, base_time: datetime
) -> tuple[datetime, datetime]:
    timestamps: list[datetime] = []
    for i in range(count):
        path = files_dir / f"invoice_{i:04d}.{extension}"
        path.write_bytes(FAKE_ENCRYPTED_CONTENT)
        # Spread across a couple of minutes, well inside the correlation
        # engine's burst window, to mimic a fast automated encryption pass.
        mtime = base_time + timedelta(seconds=i * 2)
        _set_mtime(path, mtime)
        timestamps.append(mtime)
    return min(timestamps), max(timestamps)


def _write_ransom_note(files_dir: Path, when: datetime) -> None:
    path = files_dir / "README_RESTORE_FILES.txt"
    path.write_text(RANSOM_NOTE_TEXT, encoding="utf-8")
    _set_mtime(path, when)


def _set_mtime(path: Path, when: datetime) -> None:
    ts = when.timestamp()
    import os

    os.utime(path, (ts, ts))


def _write_registry_fixture(registry_dir: Path, when: datetime) -> Path:
    hive_path = registry_dir / "synthetic_system_software.hiv"
    with SyntheticHiveBuilder(hive_path) as hive:
        hive.set_value(
            r"Software\Microsoft\Windows\CurrentVersion\Run",
            FAKE_RUN_VALUE_NAME,
            REG_SZ,
            FAKE_RUN_VALUE_DATA,
        )
        hive.set_value(
            rf"Services\{FAKE_SERVICE_NAME}",
            "ImagePath",
            REG_SZ,
            FAKE_SERVICE_IMAGE_PATH,
        )
        hive.set_value(
            rf"Services\bam\State\UserSettings\{FAKE_SID}",
            r"C:\Windows\System32\vssadmin.exe",
            REG_BINARY,
            filetime_bytes(when),
        )
    return hive_path


def _write_eventlog_fixture(eventlogs_dir: Path, when: datetime) -> Path:
    path = eventlogs_dir / "synthetic_events.json"
    records = [
        {
            "timestamp": when.isoformat(),
            "event_id": 4688,
            "provider": "Microsoft-Windows-Security-Auditing",
            "description": "New Process Name: C:\\Windows\\System32\\vssadmin.exe",
            "command_line": "vssadmin.exe delete shadows /all /quiet",
        }
    ]
    path.write_text(json.dumps(records, indent=2), encoding="utf-8")
    return path


def generate_synthetic_incident(
    output_dir: str | Path,
    num_encrypted_files: int = 40,
    num_benign_files: int = 15,
    ransom_extension: str = "locked_demo",
    include_registry: bool = True,
) -> Path:
    """Generate a complete, benign Mode B artifact folder at `output_dir` and
    return its path. `include_registry` can be set False on non-Windows
    platforms, where the hive writer (see hive_writer.py) is unavailable -
    the filesystem and event-log artifacts still work everywhere."""
    root = Path(output_dir)
    files_dir = root / "files"
    registry_dir = root / "registry"
    eventlogs_dir = root / "eventlogs"
    for d in (files_dir, registry_dir, eventlogs_dir):
        d.mkdir(parents=True, exist_ok=True)

    now = datetime.now(timezone.utc)

    _write_benign_files(files_dir, num_benign_files, now)
    burst_start, burst_end = _write_encrypted_batch(
        files_dir, num_encrypted_files, ransom_extension, now
    )
    _write_ransom_note(files_dir, burst_end)

    incident_time = burst_end + timedelta(seconds=5)
    _write_eventlog_fixture(eventlogs_dir, incident_time)

    if include_registry:
        try:
            _write_registry_fixture(registry_dir, incident_time)
        except HiveWriterUnavailable:
            if platform.system() == "Windows":
                raise

    return root
